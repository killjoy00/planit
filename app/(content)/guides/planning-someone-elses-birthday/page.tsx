import { Article, guideMetadata } from "@/components/content/Article"

const SLUG = "planning-someone-elses-birthday"

export const metadata = guideMetadata(SLUG)

export default function Page() {
  return (
    <Article slug={SLUG}>
      <p>
        Organizing something for someone else inverts every normal rule of group planning. You
        cannot ask the one person who knows all the answers. The guest list is a map of a social
        world you can only partly see. And the usual fallback &mdash; put it to a vote &mdash;
        does not apply, because the only opinion that really matters is the one you are trying not
        to consult.
      </p>
      <p>
        Most of the difficulty is concentrated in two decisions made early: whether it is a
        surprise, and who is on the list.
      </p>

      <h2>First, be honest about the surprise</h2>
      <p>
        Surprise parties are more often for the organizer than for the recipient. They are
        wonderful for people who like being the center of attention and genuinely unpleasant for
        people who do not &mdash; and the second group is larger than the first.
      </p>
      <p>Ask yourself, specifically, rather than in general:</p>
      <ul>
        <li>
          Have they ever <em>said</em> they would like one? Not &ldquo;would enjoy a party&rdquo;
          &mdash; would enjoy being surprised.
        </li>
        <li>
          How do they react to unexpected attention in a room? A person who visibly dislikes being
          sung to in a restaurant is telling you something.
        </li>
        <li>
          Do they need control over how they show up &mdash; what they are wearing, whether
          they&rsquo;ve had a bad day? For a lot of people this alone rules it out.
        </li>
      </ul>
      <p>
        The hybrid is usually the right answer and almost nobody considers it: <strong>they know
        there is a party, they do not know the details.</strong> They get to look forward to it,
        clear the evening properly, and turn up as themselves; you keep the guest list, the venue,
        and whoever flew in as the surprise. You lose the reveal and keep almost everything that
        actually makes the evening good.
      </p>

      <h2>Recruit exactly one confidant</h2>
      <p>
        You need somebody inside their life: a partner, a sibling, a roommate, the oldest friend.
        This is not optional, and it is the difference between a party that fits the person and one
        that is aimed at your idea of them.
      </p>
      <p>What the confidant is for:</p>
      <ul>
        <li>
          <strong>Securing the date.</strong> They can make sure the evening is free without
          explaining why, which you cannot.
        </li>
        <li>
          <strong>Vetting the guest list</strong> &mdash; the single most valuable thing they do.
          See below.
        </li>
        <li>
          <strong>Reality-checking the plan.</strong> &ldquo;She&rsquo;d hate that&rdquo; is worth
          more than three weeks of your own guessing.
        </li>
        <li>
          <strong>Delivering them to the right place at the right time</strong>, if there is a
          reveal.
        </li>
      </ul>
      <p>
        One confidant, not four. Every additional person who knows multiplies both the chance of a
        leak and the amount of coordination you are doing.
      </p>

      <h2>The guest list is where the real risk lives</h2>
      <p>
        This is the part that goes wrong, and it goes wrong in two directions. You invite someone
        they have quietly fallen out with, or you leave out someone who should obviously have been
        there. You will not reliably know about either, because people do not narrate their
        friendship admin.
      </p>
      <p>Three principles that reduce the damage:</p>
      <ul>
        <li>
          <strong>Have the confidant read the list before anything is sent.</strong> Not for
          approval of the party &mdash; specifically to check names. Ask directly: is anyone here a
          problem, and is anyone missing?
        </li>
        <li>
          <strong>Err smaller and closer.</strong> Fifteen people who genuinely know them beats
          forty acquaintances, and the smaller the group the fewer chances there are for an
          awkward pairing. Nobody has ever wished their birthday had been more diluted.
        </li>
        <li>
          <strong>Do not mix circles that do not already mix.</strong> Work colleagues plus college
          friends plus family is a lot to ask of the person at the center, who now has to be three
          different versions of themselves in one room. If you do combine circles, give the evening
          a structure that lets people move.
        </li>
      </ul>

      <h2>Get their preferences without asking for them</h2>
      <p>
        You do have data; it is just indirect. What did they arrange for themselves last year, and
        did it look like a relief or a chore? Where do they suggest going when it is their choice?
        Do they stay late or leave early? Are they happier in a booth with five people or a room
        with thirty?
      </p>
      <p>
        The most common failure here is scale. Organizers reach for something big because big feels
        generous, and for a fairly large share of people a loud venue full of near-strangers is the
        opposite of a gift. Match the format to how the person actually likes to spend an evening,
        not to what looks like a celebration from the outside.
      </p>

      <h2>Their availability outranks everything</h2>
      <p>
        Obvious and still worth stating, because the usual polling machinery inverts it. Do not run
        an availability poll among fifteen guests and then check whether the winning date works for
        the person the party is for. Fix their date first &mdash; through the confidant if it is a
        surprise &mdash; and let everyone else vote only on what remains.
      </p>
      <p>
        A related trap: the actual birthday is often the worst available date, because family have
        first claim on it. The weekend before is usually better than the weekend after; enthusiasm
        decays once the day has passed.
      </p>

      <h2>Handle the gift like a separate project</h2>
      <p>
        Group gifts go wrong in predictable ways, and all of them are avoidable:
      </p>
      <ul>
        <li>
          <strong>One person collects, one gift.</strong> Parallel efforts produce two of the same
          thing and an awkward conversation.
        </li>
        <li>
          <strong>Name an amount, and name a lower one.</strong> &ldquo;Around $25 if you want in
          &mdash; less is completely fine, and so is not contributing.&rdquo; Without the second
          half, the number becomes a floor and quietly excludes people.
        </li>
        <li>
          <strong>Never make contributions visible.</strong> Not who gave, not how much. Collect
          privately, and let the card say &ldquo;from everyone.&rdquo;
        </li>
        <li>
          <strong>Ask separately about the cost of attending.</strong> A dinner at $70 a head plus
          a gift contribution is a real amount of money, and people need to know both numbers
          before they answer.
        </li>
      </ul>

      <h2>Do not over-program the evening</h2>
      <p>
        Two anchors is plenty: the thing everyone is there for, and one moment &mdash; the cake,
        the toast, the photograph. Beyond that, leave it alone. Scheduled activities at a party
        mostly serve the organizer&rsquo;s anxiety, and they force the guest of honor to keep being
        summoned instead of actually talking to people.
      </p>
      <p>
        Assign two jobs for the day itself so you are not doing everything: someone on arrivals, who
        greets people and knows the plan, and someone on the person of honor, who makes sure they
        have a drink, are not stuck with one guest for an hour, and get to eat something.
      </p>

      <h2>If there is a reveal, plan the five minutes precisely</h2>
      <p>
        Everything that goes wrong with a surprise goes wrong in the arrival. Decide exactly: what
        time guests must be in place, when the confidant leaves with them, what the cover story is,
        and what happens if they are twenty minutes late.
      </p>
      <p>
        Give guests an arrival time well before the real one &mdash; thirty minutes is not
        excessive &mdash; because a group told to arrive at seven contains someone who arrives at
        seven twenty, and on a normal evening that is fine.
      </p>

      <h2>When fewer people can come than you hoped</h2>
      <p>
        It happens, and it feels like a failure at the time. Go ahead anyway, and do not tell the
        person how many people declined. They are not counting; they will only start if you hand
        them the number.
      </p>
      <p>
        A quiet dinner with six people who care about them is a genuinely good birthday. A big
        party that got postponed twice and then did not happen is not, and the pull toward the
        second is the same pull that kills every other kind of group plan &mdash; waiting for
        everyone. Send photos to the people who could not make it afterward. That is most of what
        they wanted from being invited anyway.
      </p>
    </Article>
  )
}
