import { Article, guideMetadata } from "@/components/content/Article"

const SLUG = "the-etiquette-of-dropping-out"

export const metadata = guideMetadata(SLUG)

export default function Page() {
  return (
    <Article slug={SLUG}>
      <p>
        Everyone eventually has to pull out of something they said yes to. It is not a character
        flaw and it does not need to cost you anything socially. What separates a cancellation
        nobody remembers from one that quietly changes how a group sees you is almost entirely
        timing and phrasing &mdash; not the reason, and not how sorry you are.
      </p>

      <h2>The cost of cancelling is a function of when</h2>
      <p>
        It helps to see the escalation explicitly, because people tend to treat all cancellations
        as roughly equivalent and they are not:
      </p>
      <table>
        <thead>
          <tr>
            <th>When</th>
            <th>What it costs</th>
          </tr>
        </thead>
        <tbody>
          <tr>
            <td>Before anything is booked</td>
            <td>Almost nothing. Genuinely fine.</td>
          </tr>
          <tr>
            <td>After booking, before the headcount is fixed</td>
            <td>A phone call for the organizer.</td>
          </tr>
          <tr>
            <td>After deposits or a locked headcount</td>
            <td>Real money, usually spread across everyone else.</td>
          </tr>
          <tr>
            <td>The day itself</td>
            <td>Money, an empty seat, and a plan built partly around you.</td>
          </tr>
        </tbody>
      </table>
      <p>
        Everything below follows from that table. The whole skill is moving your cancellation as
        far up it as possible.
      </p>

      <h2>1. The moment you know, say it</h2>
      <p>
        This is the entire thing. Nothing else you do matters half as much.
      </p>
      <p>
        People delay because they are hoping it will still work out, and because saying it makes
        it real. Both are understandable and both make it worse, because the cost is rising the
        whole time you are deciding. A cancellation eleven days out is an administrative note. The
        same cancellation the night before is a problem you have handed to someone else.
      </p>
      <p>
        And if you are genuinely unsure, say <em>that</em>, now. &ldquo;There&rsquo;s maybe a
        one-in-three chance I get out of this work thing &mdash; plan without me and I&rsquo;ll
        turn up if I can&rdquo; is enormously more useful than silence followed by a late no. It
        lets the organizer book for the number that is real.
      </p>

      <h2>2. Tell the organizer, not the group thread</h2>
      <p>
        Cancellations are contagious in a way that surprises people. One visible drop-out in a group
        chat gives everyone else permission &mdash; the person who was on the fence reads it as a
        signal the plan is wobbling, and within an hour you have three. Organizers watch this
        happen and it is why late public cancellations sting more than the individual absence
        warrants.
      </p>
      <p>
        Send it directly to whoever is running it. They can absorb it, adjust the booking, and
        mention it or not as they judge. If the group needs to know, it is their call and it lands
        much better coming as &ldquo;we&rsquo;re seven now&rdquo; than as a defection.
      </p>

      <h2>3. Keep the reason short</h2>
      <p>
        A long explanation feels like courtesy and reads like guilt. It also invites negotiation
        &mdash; the more detail you supply, the more surface there is for someone to helpfully
        suggest a way around it, and now you are defending your reason instead of having cancelled.
      </p>
      <blockquote>
        Sorry &mdash; I&rsquo;m not going to make Saturday. Have a good one, and I&rsquo;m in for
        the next.
      </blockquote>
      <p>
        That is complete. It contains an apology, a decision, and a signal of continued interest.
        Nobody who receives it needs more, and almost nobody wants more. The exception is when the
        reason genuinely matters to them &mdash; if you are cancelling because the plan changed in
        a way that excluded you, that is worth saying plainly rather than swallowing.
      </p>

      <h2>4. Pay what you owe, without being asked</h2>
      <p>
        If a deposit is down, if the restaurant charges for no-shows, if the house was booked for a
        number that included you &mdash; your share is a real debt, and offering it before anyone
        raises it is the single act that most preserves goodwill.
      </p>
      <p>
        Organizers overwhelmingly do not want to invoice their friends. Left to them, they will
        usually absorb it and say nothing, and then quietly remember. Pre-empting that costs you
        the money you already owed and buys you the entire reputational difference between
        &ldquo;had to drop out&rdquo; and &ldquo;dropped out and left us covering it.&rdquo;
      </p>
      <p>
        This works in the other direction too: groups should state the rule in advance. &ldquo;From
        the deposit date, if you drop out your share is covered by you unless we can fill the
        spot&rdquo; is accepted readily when announced early and resented enormously when
        discovered late.
      </p>

      <h2>5. Do not ask the group to move for you</h2>
      <p>
        Cancelling and requesting a reschedule are different actions with very different costs, and
        they should not be bundled. &ldquo;I can&rsquo;t do Saturday, could we do Sunday
        instead?&rdquo; sounds accommodating and asks seven people to redo a decision that already
        cost them something.
      </p>
      <p>
        Cancel cleanly. If you genuinely want to propose a move, make it a separate, explicit
        request with an acknowledgment of what you are asking &mdash; and accept a no immediately.
        The exception is if you are structurally necessary to the plan: it is your house, your car,
        your equipment. Then the plan does have to change, and the right move is to say so early
        and, ideally, to arrange the replacement yourself.
      </p>

      <h2>6. Watch the second one</h2>
      <p>
        One cancellation is an event. Two in a row with the same group is a pattern, and it is the
        point at which people stop counting on you &mdash; usually without deciding to, and usually
        without telling you.
      </p>
      <p>
        If you find yourself cancelling on the same group twice running, name it: &ldquo;I know
        I&rsquo;ve bailed twice, I&rsquo;m genuinely in for the next one.&rdquo; Then be in for the
        next one. Acknowledging the pattern resets it; ignoring it lets it harden into how people
        think of you.
      </p>
      <p>
        The deeper fix is upstream. Most bad cancellations start as a yes that was never really a
        yes &mdash; agreed to in the moment because declining felt awkward. Declining at the
        invitation stage is free and takes one tap. Declining three weeks later, after the booking,
        costs everyone. If you are at sixty percent on something, say sixty percent.
      </p>

      <h2>If you are the one receiving it</h2>
      <p>
        Take it gracefully and take it once. &ldquo;No worries &mdash; catch you next time&rdquo;
        is the whole correct response. Do not ask for the reason, do not express disappointment in
        a way that requires managing, and do not raise it later.
      </p>
      <p>
        The reason this is worth discipline: how you handle cancellations determines how fast
        people tell you about the next one. A group where dropping out is met with visible
        irritation is a group where people go quiet instead of answering &mdash; and a silence is
        far more expensive to you than an early no.
      </p>
      <p>
        For the genuinely chronic case, handle it structurally rather than emotionally. Stop
        counting that person in the headcount, keep inviting them, and let them come when they
        come. It costs you nothing, it costs them nothing, and it is a much better outcome than the
        conversation you are considering having.
      </p>

      <h2>The exceptions</h2>
      <p>
        Illness, emergencies, and things that are genuinely not your call are exempt from all of
        the above except the first rule &mdash; tell them as soon as you know. Nobody needs an
        apology for being ill, and nobody sensible is keeping score on it.
      </p>
      <p>
        Money is close to exempt too, and is worth saying out loud rather than inventing a
        conflict: &ldquo;this one&rsquo;s a bit beyond me this month&rdquo; is a completely
        acceptable sentence, and it is much better information for the group than a vague excuse
        &mdash; not least because a decent group will pick somewhere cheaper next time.
      </p>
    </Article>
  )
}
